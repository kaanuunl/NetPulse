const DICTIONARIES = { tr: TR, en: EN };
const LOCALES = { tr: "tr-TR", en: "en-GB" };

function lookup(dictionary, key) {
  return key.split(".").reduce((node, part) => (node && typeof node === "object" ? node[part] : undefined), dictionary);
}

export const i18n = {
  language: "en",
  locale: LOCALES.en,

  set(language) {
    this.language = DICTIONARIES[language] ? language : "en";
    this.locale = LOCALES[this.language];
  },

  t(key, params = {}, fallback) {
    const value = lookup(DICTIONARIES[this.language], key) ?? lookup(TR, key);
    if (value === undefined) return fallback ?? key;
    if (typeof value !== "string") return value;
    return value.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  },
};
